import json

from . import keys
from .config import COLLAPSE_NAME_MAPPING

HEADER = """\
// Generated by `make keys-js` from ocp_viewer_core/keys.py and config.py.
// Do not edit: change the Python side and run `make keys-js` again.
"""


def renderer_names():
    """Every setting's name on the wire, as `keys.to_javascript` spells it."""
    return {key: next(iter(keys.to_javascript({key: None}))) for key in sorted(keys.ALL)}


def live_settings():
    """The settings a host pushes to an open viewer.

    Those the viewer reports in its status (`keys.CONFIG`) - only their old values
    would win over a changed setting at the next show - and can apply while open
    (`keys.SETTABLE`). Every other setting wins at the next show anyway, and some
    must not be applied now: `reset_camera` would move the camera.
    """
    return sorted(set(keys.CONFIG) & set(keys.SETTABLE))


def value_names():
    """The stored values of live settings that `Config.workspace_config` converts."""
    return {
        "collapse": {name: member.value for name, member in COLLAPSE_NAME_MAPPING.items()},
    }


def _js(value):
    return json.dumps(value, indent=2)


def module_text():
    """The text of `js/src/keys.js`."""
    return (
        HEADER
        + "\n/** A setting's Python name, and the name a viewer takes it under. */\n"
        + f"export const RENDERER_NAMES = Object.freeze({_js(renderer_names())});\n"
        + "\n/** The settings an open viewer reports and applies: what a host pushes. */\n"
        + f"export const LIVE_SETTINGS = Object.freeze({_js(live_settings())});\n"
        + "\n/** Stored values that are converted on their way to the viewer. */\n"
        + f"export const VALUE_NAMES = Object.freeze({_js(value_names())});\n"
    )


if __name__ == "__main__":
    print(module_text(), end="")
